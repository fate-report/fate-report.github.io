/// PromptBuilder — 범용 사주·운세·궁합 AI 마스터 엔진 (K01~K10 100% 무삭제 확장판 + 4인 JEV 하네스 락).
/// 앱 코드(SajuCalculator, CompatEngine)가 계산한 K04 확정 명식 및 K07-R3 채점표를
/// 동적 슬롯에 고정(Lock) 주입하고, AI는 K01~K10 전수 대조 및 4인 하네스 검증을 거쳐 응답한다.
class PromptBuilder {
  /// 실시간 현재 날짜·세운·월운·일진 및 사용자/상대 나이 고정 잠금 블록 (KST 단일 기준 · 음력 변환 반영)
  static String buildTemporalLockBlock({
    DateTime? now,
    UserProfile? user,
    PartnerProfile? partner,
  }) {
    final dt = SajuCalculator.nowKst(now);
    final todaySaju = SajuCalculator.calculate(
      year: dt.year,
      month: dt.month,
      day: dt.day,
      hour: dt.hour,
      minute: dt.minute,
      applyLocalTime: false,
    );
    final seunYear = SajuCalculator.activeSeunYear(dt);
    final thisYearGanji = SajuCalculator.seunPillarOfYear(seunYear);
    final nextYearGanji = SajuCalculator.seunPillarOfYear(seunYear + 1);
    final prevYearGanji = SajuCalculator.seunPillarOfYear(seunYear - 1);

    String ageLock = '';
    String? dmForMonth;
    if (user?.birthDate != null) {
      final (manAge, krAge) = SajuCalculator.calculateAges(
        user!.birthDate!,
        user.calendarType,
        now: dt,
      );
      ageLock +=
          '\n- 본인 현재 나이(${dt.year}년 기준): 만 $manAge세 (연 나이 $krAge세)';
      final uSaju = user.toSaju();
      if (uSaju.dayMaster.isNotEmpty) dmForMonth = uSaju.dayMaster;
    }
    if (partner?.partnerBirthDate != null) {
      final (pManAge, pKrAge) = SajuCalculator.calculateAges(
        partner!.partnerBirthDate!,
        partner.partnerCalendarType,
        now: dt,
      );
      ageLock +=
          '\n- 상대 현재 나이(${dt.year}년 기준): 만 $pManAge세 (연 나이 $pKrAge세)';
    }

    final thisYearMonths = SajuCalculator.buildYearlyMonthPillars(
      dt.year,
      dayMaster: dmForMonth,
    );
    final nextYearMonths = SajuCalculator.buildYearlyMonthPillars(
      dt.year + 1,
      dayMaster: dmForMonth,
    );

    return '''[0. 절대 시점 및 세운·월운·나이 기준 Lock (Temporal Hard Lock — 하네스 1 최우선 강제)]
- 오늘 실시간 날짜(KST): ${dt.year}년 ${dt.month}월 ${dt.day}일
- '올해(현재 연도 세운, K03 입춘 기준)' = ${dt.year}년 $thisYearGanji년 세운 | '작년' = ${dt.year - 1}년 $prevYearGanji년 | '내년' = ${dt.year + 1}년 $nextYearGanji년
- '이번 달(현재 절기 월운, K02·K05)' = ${todaySaju.monthPillar}(${todaySaju.monthPillarHanja})월 | '오늘 일진' = ${todaySaju.dayPillar}(${todaySaju.dayPillarHanja})일$ageLock
- 올해(${dt.year}년) 1~12월 절기 월운 조견표(특정 월·시기 질문 시 즉시 참조): $thisYearMonths
- 내년(${dt.year + 1}년) 1~12월 절기 월운 조견표: $nextYearMonths
- [절대 금지 경고]: 사전학습 데이터의 과거 시점인 "2024년(갑진년)"이나 "2025년(을사년)"을 '올해/현재'라고 부르거나 2024년 기준으로 나이와 대운을 역산하는 행위를 절대 금지합니다. 모든 '올해/이번 달/지금' 표현은 반드시 ${dt.year}년($thisYearGanji년) 기준이어야 합니다.''';
  }

  /// 사용자 자유 질문(STEP 3)의 의도·도메인·형식(단문/비교/전문명리/구체적 고민)을 판별하여
  /// 고정된 틀이나 바넘 효과식 사주 일반론을 100% 차단하고 질문의 급소(과녁)를 정밀 타격하도록 만드는 지침 생성기
  static ({
    bool hasCustomQuestion,
    bool isShortRequest,
    bool isComparison,
    bool isTechnicalMyeongri,
    String topTargetHeader,
    String directiveBlock,
  }) _analyzeQuestionIntent({
    required String userQuestion,
    required String callName,
    required String partnerName,
    required bool hasPartner,
    required bool isCompatCategory,
  }) {
    final q = userQuestion.trim();
    final hasCustom = q.isNotEmpty;

    final isShort = hasCustom &&
        RegExp(r'(한\s*줄|짧게|결론만|간단히|핵심만|점수만|요약만)').hasMatch(q);

    final isTech = hasCustom &&
        RegExp(r'(명리|용신|희신|기신|십성|십신|지장간|12운성|격국|조후|억부|합충|형충|통근|투간|원국|자세히\s*설명|근거)')
            .hasMatch(q);

    final isComp = hasCustom &&
        (RegExp(r'(vs|VS|비교|중에서|중에\s|어디가|어느\s*쪽|언제가|할까\s*말까|나을까|좋을까|갈까\s*말까|이직할까|창업할까|연락할까|기다릴까|헤어질까|만날까)')
                .hasMatch(q) ||
            (q.contains('할까') && (q.contains('아니면') || q.contains('그냥'))));

    if (!hasCustom) {
      final bodyRule = isCompatCategory
          ? '- 정량 요약 아래에는 **첫 문장 명확한 결론**을 제시한 뒤, 굵은 소제목(예: `**두 사람이 서로에게 끌리는 진짜 이유**`, `**현실 연애와 대화에서 부딪히기 쉬운 순간**`, `**올해 관계 흐름과 맞춤 소통 전략**`)을 활용해 3~4문단(전체 650~850자 이내)으로 밀도 있게 풀어주세요. 각 문단에서 가장 핵심이 되는 구절은 `**굵은 글씨**`로 감싸 시각적 포인트를 잡아주세요.'
          : '- 글머리 기호(•, -)나 번호 매기기(1., 2.)를 쓰지 말고, 순수 문단 줄바꿈(\\n\\n)으로만 친한 전문가가 카톡으로 이야기해 주듯 3~4개 문단(각 문단 2~3문장, 전체 650~850자 이내)으로 밀도 있게 작성하세요. 각 문단에서 가장 핵심이 되는 구절 1곳은 `**굵은 글씨**`로 감싸 시각적 포인트를 잡아주고, 하위 리스트(`goodPoints`, `riskPoints`, `actionItems`)는 각 2개씩(1문장)만 간결히 작성해 JSON 토큰 잘림을 방지하세요.';
      return (
        hasCustomQuestion: false,
        isShortRequest: false,
        isComparison: false,
        isTechnicalMyeongri: false,
        topTargetHeader: '',
        directiveBlock: bodyRule,
      );
    }

    // 질문 도메인별 핀포인트 과녁 매칭 (Node A 정량 타겟팅)
    String domainTargetGuide = '';
    if (RegExp(r'(이직|퇴사|취업|회사|직장|부서|상사|승진|그만|면접)').hasMatch(q)) {
      domainTargetGuide =
          '   - **[🎯 이직·직장 도메인 급소 조준]**: ① 지금 움직일지(이직/지원) vs 버틸지 첫 문장에서 7:3 이상 뚜렷한 방향타를 잡으세요. ② 사주의 `월주(직장·사회궁)`와 `관성(조직)/인성(문서·계약)`이 올해 세운·월운과 합(잔류/안정)하는지 충(이동/변동수)하는지 근거로 왜 지금 마음이 흔들리는지 짚고, ③ 위 [결정적 타이밍 월] 데이터를 바탕으로 **구체적으로 몇 월에 지원·이동해야 문서와 자리가 잡히는지** 정확한 달(月)을 찍어주세요.';
    } else if (RegExp(r'(속마음|연락|재회|전남친|전여친|썸|좋아|먼저|기다|카톡|차단|생각)').hasMatch(q)) {
      domainTargetGuide =
          '   - **[🎯 연애 속마음·연락·재회 도메인 급소 조준]**: ① 상대가 지금 나를 어떻게 생각하는지(호감·미련이 남은 상태인지 vs 자존심 방어막·회피 상태인지), 그리고 **내가 지금 먼저 연락/행동해도 되는지 vs 기다려야 하는지** 첫 문장에 단호하게 결론 내리세요. ② 상대(또는 본인)의 일간·일지(배우자궁)·식상(표현력) 구조를 근거로 상대가 왜 그런 태도를 보이는지 심리를 해부하고, ③ **상대 마음이 열리는 구체적 시기(몇 월)와 상대 기질에 가장 잘 먹히는 실제 카톡 문구·대화 톤**을 콕 집어 알려주세요.';
    } else if (RegExp(r'(돈|재물|투자|주식|코인|부동산|매매|계약|창업|사업|부업|매출|금전)').hasMatch(q)) {
      domainTargetGuide =
          '   - **[🎯 재물·투자·창업 도메인 급소 조준]**: ① 지금이 **공격적으로 벌리고 들어갈 타이밍인지 vs 현금을 지키고 관망할 타이밍인지** 첫 문장에 명확히 판정하세요. ② 사주의 `식상(수익 창출) → 재성(현금 결실)` 유통 경로와 `인성(문서·계약)`/`비겁(손재·경쟁)` 구조를 근거로 내 돈이 모이는 방식과 새는 구멍을 짚고, ③ 올해/내년 월운 중 **금전·계약에 가장 유리한 달(몇 월)과 피해야 할 달(몇 월)**을 구체적으로 찍어주세요.';
    } else if (RegExp(r'(시험|합격|자격증|공부|공무원|입시|붙을|학업)').hasMatch(q)) {
      domainTargetGuide =
          '   - **[🎯 시험·합격 도메인 급소 조준]**: ① 합격·문서운(`인성·관성`)이 시험 시기에 강하게 들어오는지 첫 문장에 명확히 답하세요. ② 실전에서 내 점수를 깎아먹는 사주상 멘탈 약점(조급함/완벽주의 등)을 짚고, ③ 남은 기간 합격률을 극대화할 실전 공부·컨디션 전략을 제시하세요.';
    } else {
      domainTargetGuide =
          '   - **[🎯 질문 핵심 급소 조준]**: 사용자가 물은 "$q"에서 진짜로 결정하고 싶어 하는 핵심 포인트(Yes/No/언제/왜/어떻게)를 정확히 겨냥하여, 추상적인 말 대신 구체적인 시기(몇 월)와 실제 상황 장면이 눈에 그려지게 직답하세요.';
    }

    final topHeader = '''
====================================================================
[🎯 0순위 절대 타겟 과녁 (Question Target Lock — 사주 일반론 나열 절대 금지)]
- 사용자가 던진 질문: "$q"
- [핵심 핀포인트 명령]:
  1) 아래 제공되는 사주 8글자·대운·월운 데이터를 처음부터 끝까지 다 설명하려 하지 마세요! 질문과 직접 상관없는 뻔한 성격 칭찬("원래 책임감이 강하고 내면의 기준이 뚜렷한 분이라..." 등 바넘 효과식 서론)은 100% 삭제하세요.
  2) 첫 문장부터 마지막 문단까지 오직 "$q"의 핵심 포인트를 찌르는 데만 집중하고, 애매한 양비론("신중하게 생각해보세요", "여유를 가지세요") 대신 명리적 근거에 기반한 **뚜렷한 판정(최소 7:3의 명확한 방향타)과 구체적 시기(몇 월)·구체적 행동 대사**를 제시하세요.
  3) 각 문단에서 사용자의 질문 핵심을 찌르는 **가장 중요한 핵심 결론 구절 1~2곳은 반드시 `**핵심 구절**`처럼 별표 두 개(`**`)로 감싸** 화면에서 골드 하이라이트 폰트로 눈에 확 들어오게 만드세요.
====================================================================''';

    final buffer = StringBuffer();
    buffer.writeln(
      '★ [최우선 절대 명령 — 사용자 자유 질문("$q") 과녁 정밀 타격 원칙]:',
    );
    buffer.writeln(
      '   - **뻔한 기본 성격 서론(바넘 효과) 절대 금지**: 1문단이나 2문단에서 "회원님은 겉으로는 무던해 보여도..." 같은 기본 성향 소개로 힘을 빼지 마세요! 첫 문장부터 곧바로 "$q"의 정중앙(핵심 답)을 타격하세요.',
    );
    buffer.writeln(
      '   - **양비론(5:5 회피) 금지 & 구체적 월(Month) 명시**: "장단점이 있으니 신중히 결정하세요"처럼 결정을 미루지 말고, 사주 원국과 월운 합·충을 근거로 어느 쪽이 유리한지 명확히 결론 내리고 구체적인 달(예: "올해 O월")을 찍어주세요.',
    );
    buffer.writeln(
      '   - **시각적 폰트 하이라이트(`**핵심 문장**`) 필수 적용**: 본문(`briefingBody`)의 각 문단마다 질문의 핵심을 찌르는 가장 중요한 문장이나 키워드 구절 1~2곳을 반드시 `**굵은 강조 표시**`로 감싸주세요(앱 화면에서 골드 형광펜 포인트 폰트로 렌더링됩니다).',
    );
    buffer.writeln(
      '   - **[토큰 초과(502 에러) 방지 및 밀도 압축 규칙]**: 사족이나 같은 말 반복으로 글이 길어져 JSON이 잘리지 않도록, `briefingBody`는 핵심만 날카롭게 찌르는 **3~4개 문단(각 문단 2~3문장, 전체 600~850자 이내)**으로 밀도 있게 압축하고, 하위 리스트(`goodPoints`, `riskPoints`, `actionItems`)는 각각 **핵심 2개씩(각 1문장)**만 간결하게 작성하세요.',
    );
    buffer.writeln(domainTargetGuide);

    if (isShort) {
      buffer.writeln(
        '   - **[단문/핵심 직답 모드 발동]**: 사용자가 짧고 간결한 결론을 원하므로, `briefingBody`를 1~2개의 짧은 핵심 문단(2~4문장 이내)으로 명쾌하게 직답하고, `resultSummary`는 빈 문자열(`""`), `goodPoints`, `riskPoints`, `actionItems`는 모두 빈 배열(`[]`)로 출력하세요.',
      );
    } else if (isComp) {
      buffer.writeln(
        '   - **[양자택일·비교·결정 맞춤 모드 발동]**: 첫 문장에 **"어느 쪽(또는 언제)이 더 유리한지" 명확한 최종 결론**부터 못 박고, 그 아래에는 **사용자가 질문에서 제시한 실제 선택지나 시기**를 그대로 `**굵은 소제목**`으로 삼아 각각의 기회와 리스크를 정면 비교해 주세요.',
      );
    } else {
      buffer.writeln(
        '   - **[구체적 고민 1:1 핀포인트 직답 모드 발동]**: 질문 문장 안에 담긴 모든 궁금증(왜 그런지 / 상대 속마음이 뭔지 / 언제 풀리는지 / 내가 지금 어떻게 해야 하는지)을 하나도 빠뜨리지 말고 문단별로 1:1 매칭하여 속 시원하게 직답하세요.',
      );
    }

    if (isTech) {
      buffer.writeln(
        '   - **[전문 명리 해설 허용 모드 발동 (0절 1항 예외)]**: 쉬운 결론을 먼저 말한 뒤, 실제 작용한 천간·지지·십성·지장간·12운성·조후·억부·합충 원리를 구체적인 명리 용어와 함께 상세히 풀어주세요.',
      );
    } else {
      buffer.writeln(
        '   - 전문 명리 용어(일간, 십성, 지장간, 조후, 억부, 12운성 등)는 그대로 노출하지 말고 일상 심리·대화 습관·실제 상황 장면으로 생생하게 번역해서 설명하세요.',
      );
    }

    return (
      hasCustomQuestion: true,
      isShortRequest: isShort,
      isComparison: isComp,

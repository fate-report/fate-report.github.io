## [K07-R3] 궁합 기계채점표 정량규칙 (무삭제 완전판 + 수식 근거 표기 락)
- **0. 기본 조건 및 일관성 락**: 검증된 두 사람의 년·월·일주(3주 6글자)가 확보된 뒤에만 A~D를 계산한다. 두 사람의 시주가 모두 확인된 경우에만 시주 보정을 추가하며, 한쪽이라도 시간 미상이면 양쪽 시주를 모두 제외한다(감점 없음). 동일 입력이면 언제 계산해도 1점의 오차 없이 동일한 점수와 신호등이 나와야 하며, 용신·조후·지장간·12운성·신살·세운·현재 관계 상태를 점수에 절대 섞지 않는다.
- **공통 중복 처리 원칙**: 같은 비교쌍은 항목 내 1회만 계산하며, 여러 관계가 동시에 걸리면 **절댓값이 가장 큰 점수 1개만 적용(절댓값이 같으면 감점 우선)**한다.
  - *유일한 동시 적용 예외*: A항목에서 두 일지가 같으면서 자형(`辰-辰, 午-午, 酉-酉, 亥-亥`)일 때만 같은 일지(`+3`)와 자형(`-8`)을 동시 적용해 **`-5점`**으로 계산한다. 그 외 D항목에서는 자형을 일반 형(`-2점`)에 포함하며, 시주 보정에서 시지가 같으면서 자형이면 절댓값 최대(감점 우선) 원칙에 따라 `시지 형(-3점)` 1개만 적용한다.
- **A. 관계의 중심축 (기본 25점, 항목 범위 0~35점)**: 두 일지 1:1 비교.
  - 일지 육합 `+10` / 같은 일지 `+3` / 직접 충 `-12` / 형(자형 포함) `-8` / 해 `-6` / 파 `-4` (자형일 땐 `+3`과 `-8` 동시 적용하여 `-5`)
- **B. 생각과 표현 방식 (기본 11점, 항목 범위 0~20점)**:
  - 두 일간 관계(가장 강한 1개만): 천간합 `+6` / 상생 `+3` / 같은 오행 `+1` / 상극 `-2`
  - 추가 천간합(A년간-B년간, A년간-B월간, A월간-B년간, A월간-B월간 4쌍 비교): 성립 1쌍당 `+1` (최대 `+3` 상한)
- **C. 서로 부족한 부분의 보완 (기본 12점, 항목 범위 0~25점)**:
  - 각자 3주 6글자(년·월·일간 + 년·월·일지 본기)로 木火土金水 개수 산출 (`0개=부족 / 1개=보통 / 2개 이상=강함`).
  - A의 부족(0개) 오행을 B가 2개 이상 보유 시 해당 오행당 `+3`
  - B의 부족(0개) 오행을 A가 2개 이상 보유 시 해당 오행당 `+3`
  - 두 사람이 서로 다른 부족 오행을 각각 1가지 이상 상호 보완 시 추가 `+2`
  - 동일 오행을 두 사람 모두 2개 이상 보유 시 해당 오행당 `-3` (동일 오행에 보완 가점과 과다 감점 동시 발생 불가)
  - 가점 합계 최대 `+13`, 감점 합계 최대 `-9` 적용 후 `0~25점` 제한.
- **D. 생활과 장기 안정성 (기본 10점, 항목 범위 0~20점)**: 년지-년지, 년지-월지, 월지-년지, 월지-월지 4쌍 비교.
  - 각 쌍당 가장 강한 1개만 적용: 육합 `+3` / 직접 충 `-3` / 형(자형 포함) `-2` / 해 `-2` / 파 `-1`
  - 두 사람의 년지·월지 4글자 안에 완전한 삼합 또는 방합이 성립하면 전체 1회만 `+4` (부분합 제외)
  - 4쌍 중 직접 충이 2회 이상이면 추가 `-3` / 4글자 안에 완전한 삼형이 성립하면 추가 `-5`
- **시주 보정 (양쪽 시간 모두 확인 시에만 적용, 기본 0점, 범위 -5~+5점)**:
  - 두 시지 1:1 비교(가장 강한 1개만): 시지 육합 `+3` / 같은 시지(자형 제외) `+1` / 시지 충 `-4` / 시지 형(자형 포함) `-3` / 시지 해 `-2` / 시지 파 `-1`
  - 두 시간(時干) 비교: 천간합 `+1`, 천간합이 없고 상생이면 `+1` (동시 적용 불가)
- **필수 검산 순서 및 출력 포맷 락**:
  1) 내부에서 양측 6글자 오행 개수와 A(0~35), B(0~20), C(0~25), D(0~20), 시주 보정(-5~+5)의 실제 글자 쌍을 먼저 대조·합산하고 `총점(0~100 제한) = A+B+C+D(+시주보정)` 등식이 정확히 맞는지 재검산한다.
  2) 신호등 판정: `80~100점 = GREEN(🟢)` / `50~79점 = YELLOW(🟡)` / `0~49점 = RED(🔴)` (시간 미상 시 45~54점, 75~84점이면 시주에 따라 경계 이동 가능성 안내).
  3) 화면 상단 요약창 출력 시 암산 오류 방지를 위해 반드시 **`항목명 (득점/만점): 기본 OO점 + 실제 작용 글자 및 가감점 요약`** 형태로 근거를 투명하게 명시한다.

## [K08] 사용자·타인 명식 도출 및 검증 7대 강제 브레이크 (무삭제 전체)
